import 'package:flutter/foundation.dart';

final appLanguage = ValueNotifier<String>('pt');

int? appLanguageId;

/// Indica se a interface está em inglês.
bool get isEnglish => appLanguage.value == 'en';

/// Converte o código do backend (pt-BR, en) no idioma da interface (pt, en).
String uiLanguageFor(String code) =>
    code.toLowerCase().startsWith('en') ? 'en' : 'pt';

/// Aplica o idioma retornado pela API, ignorando respostas sem código de idioma.
void applyLanguage(Object? language) {
  if (language is! Map || language['code'] is! String) return;
  appLanguage.value = uiLanguageFor(language['code'] as String);
  if (language['id'] is int) appLanguageId = language['id'] as int;
}

/// Traduz um texto fixo escrito em português para o idioma atual, mantendo o original quando não há tradução.
String tr(String pt) => isEnglish ? (enStrings[pt] ?? pt) : pt;

/// Escolhe entre a versão em português e em inglês de um texto com interpolação.
String t(String pt, String en) => isEnglish ? en : pt;

